-- =====================================================================
-- USV Sport – structura bazei de date (PostgreSQL)
-- Rulează în pgAdmin 4: click dreapta pe baza `db_campus_sports` -> Query Tool,
-- lipește tot scriptul și apasă F5.
--
-- ATENȚIE: șterge și recreează cele 5 tabele de mai jos. Datele din ele se pierd.
-- Toate orele se păstrează ca timp local (Europe/Bucharest), fără fus orar.
-- =====================================================================

DROP TABLE IF EXISTS waitlist_notifications, blocked_slots, bookings, facilities, users CASCADE;
DROP TYPE IF EXISTS user_role, facility_type, booking_status, block_reason CASCADE;
DROP FUNCTION IF EXISTS set_updated_at() CASCADE;

-- ---------- Tipuri enumerate ----------
CREATE TYPE user_role      AS ENUM ('student', 'professor', 'external', 'administrator');
CREATE TYPE facility_type  AS ENUM ('football_field', 'gym', 'swimming_pool', 'sports_hall');
CREATE TYPE booking_status AS ENUM ('confirmed', 'cancelled', 'completed');
CREATE TYPE block_reason   AS ENUM ('university_course', 'university_event', 'maintenance',
                                    'repair', 'cleaning', 'other');

-- ---------- Actualizare automată a coloanei updated_at ----------
CREATE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN
    NEW.updated_at = now() AT TIME ZONE 'Europe/Bucharest';
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- ---------- users ----------
CREATE TABLE users (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         varchar(100) NOT NULL UNIQUE,
    first_name    varchar(50)  NOT NULL,
    last_name     varchar(50)  NOT NULL,
    password_hash varchar(255) NOT NULL,
    role          user_role    NOT NULL,
    created_at    timestamp    NOT NULL DEFAULT (now() AT TIME ZONE 'Europe/Bucharest'),
    updated_at    timestamp    NOT NULL DEFAULT (now() AT TIME ZONE 'Europe/Bucharest')
);

-- ---------- facilities ----------
CREATE TABLE facilities (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        varchar(100)  NOT NULL,
    type        facility_type NOT NULL,
    capacity    integer       NOT NULL DEFAULT 1,   -- rezervări simultane (ex. 4 culoare la bazin)
    location    varchar(150)  NOT NULL,
    is_active   boolean       NOT NULL DEFAULT true,
    created_at  timestamp     NOT NULL DEFAULT (now() AT TIME ZONE 'Europe/Bucharest'),
    updated_at  timestamp     NOT NULL DEFAULT (now() AT TIME ZONE 'Europe/Bucharest'),
    CONSTRAINT ck_facilities_capacity CHECK (capacity >= 1)
);

-- ---------- bookings ----------
CREATE TABLE bookings (
    id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           integer        NOT NULL REFERENCES users (id),
    facility_id       integer        NOT NULL REFERENCES facilities (id),
    start_time        timestamp      NOT NULL,
    end_time          timestamp      NOT NULL,
    status            booking_status NOT NULL DEFAULT 'confirmed',
    early_released_at timestamp,
    created_at        timestamp      NOT NULL DEFAULT (now() AT TIME ZONE 'Europe/Bucharest'),
    updated_at        timestamp      NOT NULL DEFAULT (now() AT TIME ZONE 'Europe/Bucharest'),
    CONSTRAINT ck_bookings_interval CHECK (end_time > start_time)
);
CREATE INDEX ix_bookings_facility_start ON bookings (facility_id, start_time);
CREATE INDEX ix_bookings_user_start     ON bookings (user_id, start_time);

-- ---------- blocked_slots ----------
CREATE TABLE blocked_slots (
    id                 integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    facility_id        integer      NOT NULL REFERENCES facilities (id),
    created_by_user_id integer      NOT NULL REFERENCES users (id),
    start_time         timestamp    NOT NULL,
    end_time           timestamp    NOT NULL,
    reason             block_reason NOT NULL,
    description        text,
    created_at         timestamp    NOT NULL DEFAULT (now() AT TIME ZONE 'Europe/Bucharest'),
    updated_at         timestamp    NOT NULL DEFAULT (now() AT TIME ZONE 'Europe/Bucharest'),
    CONSTRAINT ck_blocked_slots_interval CHECK (end_time > start_time)
);
CREATE INDEX ix_blocked_slots_facility_start ON blocked_slots (facility_id, start_time);

-- ---------- waitlist_notifications ----------
-- „Anunță-mă dacă se eliberează ceva în ziua X la facilitatea Y."
CREATE TABLE waitlist_notifications (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     integer   NOT NULL REFERENCES users (id),
    facility_id integer   NOT NULL REFERENCES facilities (id),
    target_date date      NOT NULL,
    is_notified boolean   NOT NULL DEFAULT false,
    created_at  timestamp NOT NULL DEFAULT (now() AT TIME ZONE 'Europe/Bucharest'),
    updated_at  timestamp NOT NULL DEFAULT (now() AT TIME ZONE 'Europe/Bucharest'),
    CONSTRAINT uq_waitlist_user_facility_date UNIQUE (user_id, facility_id, target_date)
);

-- ---------- Triggere pentru updated_at ----------
CREATE TRIGGER trg_users_updated_at                  BEFORE UPDATE ON users                  FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_facilities_updated_at             BEFORE UPDATE ON facilities             FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_bookings_updated_at               BEFORE UPDATE ON bookings               FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_blocked_slots_updated_at          BEFORE UPDATE ON blocked_slots          FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_waitlist_notifications_updated_at BEFORE UPDATE ON waitlist_notifications FOR EACH ROW EXECUTE FUNCTION set_updated_at();
