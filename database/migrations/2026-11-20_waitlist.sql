DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'waitlist_status') THEN
        CREATE TYPE waitlist_status AS ENUM
            ('active', 'offered', 'fulfilled', 'declined', 'expired', 'cancelled');
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'notification_category') THEN
        CREATE TYPE notification_category AS ENUM
            ('booking_confirmation', 'reminder', 'cancellation', 'waitlist_offer',
             'university_activity', 'maintenance', 'incident_urgent', 'reopening');
    END IF;
END $$;

ALTER TABLE bookings ADD COLUMN IF NOT EXISTS replaced_booking_id integer REFERENCES bookings (id);

CREATE TABLE IF NOT EXISTS waitlist_entries (
    id                 integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id            integer         NOT NULL REFERENCES users (id),
    facility_id        integer         NOT NULL REFERENCES facilities (id),
    start_time         timestamp       NOT NULL,
    end_time           timestamp       NOT NULL,
    status             waitlist_status NOT NULL DEFAULT 'active',
    replace_booking_id integer         REFERENCES bookings (id),
    offered_at         timestamp,
    offer_expires_at   timestamp,
    created_at         timestamp       NOT NULL DEFAULT (now() AT TIME ZONE 'Europe/Bucharest'),
    updated_at         timestamp       NOT NULL DEFAULT (now() AT TIME ZONE 'Europe/Bucharest'),
    CONSTRAINT ck_waitlist_interval CHECK (end_time > start_time)
);
CREATE INDEX IF NOT EXISTS ix_waitlist_facility_start ON waitlist_entries (facility_id, start_time);
CREATE UNIQUE INDEX IF NOT EXISTS uq_waitlist_open_entry
    ON waitlist_entries (user_id, facility_id, start_time)
    WHERE status IN ('active', 'offered');

CREATE TABLE IF NOT EXISTS notifications (
    id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           integer               NOT NULL REFERENCES users (id),
    category          notification_category NOT NULL,
    title             varchar(150)          NOT NULL,
    body              text                  NOT NULL,
    booking_id        integer               REFERENCES bookings (id),
    waitlist_entry_id integer               REFERENCES waitlist_entries (id),
    read_at           timestamp,
    created_at        timestamp             NOT NULL DEFAULT (now() AT TIME ZONE 'Europe/Bucharest'),
    updated_at        timestamp             NOT NULL DEFAULT (now() AT TIME ZONE 'Europe/Bucharest')
);
CREATE INDEX IF NOT EXISTS ix_notifications_user_created ON notifications (user_id, created_at DESC);

DROP TRIGGER IF EXISTS trg_waitlist_entries_updated_at ON waitlist_entries;
CREATE TRIGGER trg_waitlist_entries_updated_at BEFORE UPDATE ON waitlist_entries
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
DROP TRIGGER IF EXISTS trg_notifications_updated_at ON notifications;
CREATE TRIGGER trg_notifications_updated_at BEFORE UPDATE ON notifications
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
